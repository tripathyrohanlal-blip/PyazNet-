export function projectLonLat([lon, lat]: [number, number]): [number, number] {
  const x = ((lon - 67.5) / 30.8) * 520 + 20;
  const y = ((37.6 - lat) / 30.2) * 580 + 18;
  return [Number(x.toFixed(1)), Number(y.toFixed(1))];
}

export function coordsToSvgPath(coords: [number, number][]): string {
  return (
    coords
      .map((pt, idx) => {
        const [x, y] = projectLonLat(pt);
        return `${idx === 0 ? 'M' : 'L'}${x},${y}`;
      })
      .join(' ') + ' Z'
  );
}

export function getPolygonCentroid(coords: [number, number][]): [number, number] {
  let sumX = 0;
  let sumY = 0;
  for (const pt of coords) {
    const [x, y] = projectLonLat(pt);
    sumX += x;
    sumY += y;
  }
  return [sumX / coords.length, sumY / coords.length];
}

